/**
 * Post-build step: emit the consumer-facing files that are not produced by the
 * Style Dictionary run in `config.js`.
 *
 * Currently: copy the dependency-free accent validator into `dist/` so it can
 * be published as `@palladio/tokens/validate-accents` without shipping the
 * pipeline. Run after `node pipeline/config.js`; TypeScript declaration/JS
 * emit for `dist/ts/tokens.ts` is handled separately by `tsc` in the build
 * script.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pipelineDir = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(pipelineDir, '..');
const distDir = path.join(packageDir, 'dist');

const source = path.join(pipelineDir, 'accent-contract.mjs');
const target = path.join(distDir, 'validate-accents.mjs');

const banner =
  '// Generated by the Palladio pipeline from pipeline/accent-contract.mjs. Do not edit.\n' +
  '// Published as `@palladio/tokens/validate-accents` — see palladio/README.md.\n\n';

const body = await readFile(source, 'utf8');
await writeFile(target, banner + body, 'utf8');

console.log(`Emitted ${path.relative(packageDir, target)} from ${path.relative(packageDir, source)}.`);
