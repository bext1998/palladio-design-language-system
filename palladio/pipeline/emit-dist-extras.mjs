/**
 * Post-build step: emit the consumer-facing files the Style Dictionary run in
 * `config.js` does not produce.
 *
 * 1. Copy the dependency-free accent validator to `dist/validate-accents.js` so
 *    it can be published as `@palladio/tokens/validate-accents` without the
 *    pipeline. Its `.d.ts` is emitted separately by `tsc -p tsconfig.accents.json`
 *    in the build script.
 * 2. Copy the repo-root LICENSE into the package directory so the npm tarball
 *    (and the Release asset built from it) carry the MIT text.
 *
 * Run after `node pipeline/config.js`.
 */

import { copyFile, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pipelineDir = path.dirname(fileURLToPath(import.meta.url));
const packageDir = path.resolve(pipelineDir, '..');
const repoRoot = path.resolve(packageDir, '..');
const distDir = path.join(packageDir, 'dist');

const rel = (p) => path.relative(packageDir, p);

// 1. accent validator -> dist/validate-accents.js
const accentSource = path.join(pipelineDir, 'accent-contract.mjs');
const accentTarget = path.join(distDir, 'validate-accents.js');
const banner =
  '// Generated by the Palladio pipeline from pipeline/accent-contract.mjs. Do not edit.\n' +
  '// Published as `@palladio/tokens/validate-accents` — see palladio/README.md.\n\n';
await writeFile(accentTarget, banner + (await readFile(accentSource, 'utf8')), 'utf8');
console.log(`Emitted ${rel(accentTarget)} from ${rel(accentSource)}.`);

// 2. LICENSE -> palladio/LICENSE (verbatim; npm wants it inside the package dir)
const licenseTarget = path.join(packageDir, 'LICENSE');
await copyFile(path.join(repoRoot, 'LICENSE'), licenseTarget);
console.log(`Copied ${rel(licenseTarget)} from repo-root LICENSE.`);
